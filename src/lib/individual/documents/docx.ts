import { AlignmentType, BorderStyle, Document, Footer, HeadingLevel, Packer, PageNumber, PageOrientation, Paragraph, TextRun, convertMillimetersToTwip } from "docx";
import type { Template } from "../documents-config";
import type { DocModel } from "./model";

// ── DOCX RENDERING OF THE ONE MODEL ── COMPETEN-PROFESSIONAL-PROGRESS-01 PR7 s10.6 ──────────────────────────────────────
//
// An editable Word document: real headings (Heading 1 per section, so Word's navigation pane and styles work), one
// paragraph per line of modelLines() in the same order, consistent styles from the template, page size, orientation and
// margins, and page numbers. The typeface pairs with the PDF's (sans: Arial / Helvetica, serif: Times New Roman / Times).

const PAGE_TWIP = { A4: { width: 11906, height: 16838 }, Letter: { width: 12240, height: 15840 } } as const;
const hex = (c: string) => c.replace("#", "").toUpperCase();
export const docxFont = (t: Template) => (t.type.face === "serif" ? "Times New Roman" : "Arial");

export async function renderDocx(m: DocModel, t: Template): Promise<Buffer> {
  const font = docxFont(t);
  const size = Math.round(t.type.base * 2);
  const line = Math.round(240 * t.type.lineSpacing);
  const run = (text: string, o: { bold?: boolean; colour?: string; size?: number; italics?: boolean } = {}) =>
    new TextRun({ text, font, bold: o.bold, italics: o.italics, color: hex(o.colour ?? t.colours.text), size: o.size ?? size });
  const p = (text: string, o: Parameters<typeof run>[1] & { after?: number; before?: number } = {}) =>
    new Paragraph({ children: [run(text, o)], spacing: { after: o.after ?? 60, before: o.before ?? 0, line } });

  const body: Paragraph[] = [];
  body.push(new Paragraph({ heading: HeadingLevel.TITLE, children: [run(m.header.name, { bold: true, colour: t.colours.accent, size: Math.round(size * t.type.headingScale * 1.5) })], spacing: { after: 80, line } }));
  if (m.header.headline) body.push(p(m.header.headline, { colour: t.colours.muted, after: 40 }));
  if (m.header.contact) body.push(p(m.header.contact, { colour: t.colours.muted, after: 40 }));
  for (const s of m.sections) {
    body.push(new Paragraph({
      heading: HeadingLevel.HEADING_1, spacing: { before: 240, after: 80, line },
      border: { bottom: { style: BorderStyle.SINGLE, size: 6, color: hex(t.colours.accent), space: 2 } },
      children: [run(s.title, { bold: true, colour: t.colours.accent, size: Math.round(size * t.type.headingScale) })],
    }));
    if (s.intro) body.push(p(s.intro, { italics: true, colour: t.colours.muted }));
    for (const para of s.paragraphs) body.push(p(para, { after: 100 }));
    for (const e of s.entries) {
      body.push(p(e.subtitle ? `${e.title}, ${e.subtitle}` : e.title, { bold: true, before: 80, after: 20 }));
      body.push(p([e.when, e.status].filter(Boolean).join(" · "), { colour: t.colours.muted, size: Math.round(size * 0.9), after: 20 }));
      for (const f of e.facts) body.push(new Paragraph({ bullet: { level: 0 }, children: [run(f, { size: Math.round(size * 0.95) })], spacing: { after: 20, line } }));
    }
  }
  if (m.legend.length) body.push(p(`Status wording: ${m.legend.join("; ")}.`, { colour: t.colours.muted, size: Math.round(size * 0.85), before: 240 }));

  const footerLines: Paragraph[] = [];
  if (m.footer) footerLines.push(new Paragraph({ alignment: AlignmentType.LEFT, children: [run(m.footer, { colour: t.colours.muted, size: Math.round(size * 0.8) })] }));
  if (t.footer.pageNumbers) footerLines.push(new Paragraph({ alignment: AlignmentType.RIGHT, children: [new TextRun({ font, size: Math.round(size * 0.8), color: hex(t.colours.muted), children: ["Page ", PageNumber.CURRENT, " of ", PageNumber.TOTAL_PAGES] })] }));

  const dims = PAGE_TWIP[t.page.size];
  const mg = t.page.margins;
  const doc = new Document({
    creator: m.author, title: m.title, subject: m.subject, description: `${m.subject}, ${m.template.name} template v${m.template.version}. Generated by Competen Document Studio.`,
    keywords: `Competen; ${m.docType}`, lastModifiedBy: "Competen Document Studio",
    styles: { default: { document: { run: { font, size, color: hex(t.colours.text) } } } },
    sections: [{
      properties: { page: {
        size: { width: dims.width, height: dims.height, orientation: t.page.orientation === "landscape" ? PageOrientation.LANDSCAPE : PageOrientation.PORTRAIT },
        margin: { top: convertMillimetersToTwip(mg.top), right: convertMillimetersToTwip(mg.right), bottom: convertMillimetersToTwip(mg.bottom), left: convertMillimetersToTwip(mg.left) },
      } },
      footers: footerLines.length ? { default: new Footer({ children: footerLines }) } : undefined,
      children: body,
    }],
  });
  return Packer.toBuffer(doc);
}
