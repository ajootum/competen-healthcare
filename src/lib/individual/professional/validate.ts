import { CPD_ACTIVITY, EVIDENCE_KIND, GOAL_STATUS, NEED_STATUS, type CpdActivity, type EvidenceKind, type GoalStatus, type NeedStatus } from "./vocabulary";

// ── INPUT VALIDATION FOR THE PROFESSIONAL RECORD ── pure, and the same limits as migration 373 ─────────
//
// Every API route parses its body here before it writes, so a request the schema would refuse is
// refused with a sentence instead of a constraint name. The limits mirror 373's CHECKs. The schema
// remains the rule; this is the explanation.
//
// ⚠ NOTHING HERE ACCEPTS A CLASS, A VERIFIED FLAG OR A USER ID. The evidence class is generated by the
// database, and the owner is always the guarded caller. A body that carries any of them is simply not
// read for it.

export type Parsed<T> = { ok: true; value: T } | { ok: false; error: string };

const UUID = /^[0-9a-f]{8}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{12}$/i;
export const isUuid = (v: unknown): v is string => typeof v === "string" && UUID.test(v);

/** Trimmed text, or null when blank. `undefined` when it is too long, so the caller can say so. */
function text(v: unknown, max: number): string | null | undefined {
  if (v === null || v === undefined) return null;
  if (typeof v !== "string") return undefined;
  const t = v.trim();
  if (!t) return null;
  return t.length > max ? undefined : t;
}

/** A calendar date as YYYY-MM-DD that really exists, or null when blank. `undefined` when malformed. */
export function isoDate(v: unknown): string | null | undefined {
  if (v === null || v === undefined || v === "") return null;
  if (typeof v !== "string" || !/^\d{4}-\d{2}-\d{2}$/.test(v)) return undefined;
  const d = new Date(`${v}T00:00:00Z`);
  return Number.isNaN(d.getTime()) || d.toISOString().slice(0, 10) !== v ? undefined : v;
}

function optUuid(v: unknown): string | null | undefined {
  if (v === null || v === undefined || v === "") return null;
  return isUuid(v) ? v : undefined;
}

function title(v: unknown): string | null {
  const t = text(v, 200);
  return t && t.length >= 3 ? t : null;
}

const oneOf = <T extends string>(list: readonly (readonly [T, string])[], v: unknown): T | null =>
  typeof v === "string" && list.some(([k]) => k === v) ? (v as T) : null;

// ── PROFILE ─────────────────────────────────────────────────────────────────────────────────────────

export type ProfileInput = {
  self_declared_profession: string | null;
  self_declared_registration_body: string | null;
  self_declared_registration_number: string | null;
  self_declared_registration_country: string | null;
  self_declared_registration_expires_on: string | null;
};

export function parseProfile(b: Record<string, unknown>): Parsed<ProfileInput> {
  const profession = text(b.profession, 120);
  const body = text(b.registrationBody, 160);
  const number = text(b.registrationNumber, 60);
  const country = text(b.country, 80);
  const expires = isoDate(b.registrationExpiresOn);
  if (profession === undefined) return { ok: false, error: "Profession can be up to 120 characters." };
  if (body === undefined) return { ok: false, error: "Registration body can be up to 160 characters." };
  if (number === undefined) return { ok: false, error: "Registration number can be up to 60 characters." };
  if (country === undefined) return { ok: false, error: "Country can be up to 80 characters." };
  if (expires === undefined) return { ok: false, error: "Enter the registration expiry as a real date." };
  return {
    ok: true, value: {
      self_declared_profession: profession,
      self_declared_registration_body: body,
      self_declared_registration_number: number,
      self_declared_registration_country: country,
      self_declared_registration_expires_on: expires,
    },
  };
}

// ── NEEDS ───────────────────────────────────────────────────────────────────────────────────────────

export type NeedInput = {
  title: string; detail: string | null; origin: "self_identified" | "passport_gap";
  framework_id: string | null; framework_competency_id: string | null;
};

export function parseNeed(b: Record<string, unknown>): Parsed<NeedInput> {
  const t = title(b.title);
  if (!t) return { ok: false, error: "Describe the need in 3 to 200 characters." };
  const detail = text(b.detail, 2000);
  if (detail === undefined) return { ok: false, error: "The detail can be up to 2,000 characters." };
  const origin = b.origin === "passport_gap" ? "passport_gap" : "self_identified";
  const fw = optUuid(b.frameworkId);
  const comp = optUuid(b.frameworkCompetencyId);
  if (fw === undefined || comp === undefined) return { ok: false, error: "That framework reference is not valid." };
  if (comp && !fw) return { ok: false, error: "Choose the framework the competency belongs to." };
  return { ok: true, value: { title: t, detail, origin, framework_id: fw, framework_competency_id: comp } };
}

export function parseNeedStatus(v: unknown): NeedStatus | null {
  return oneOf(NEED_STATUS, v);
}

// ── GOALS ───────────────────────────────────────────────────────────────────────────────────────────

export type GoalInput = { title: string; detail: string | null; target_date: string; need_id: string | null };

export function parseGoal(b: Record<string, unknown>): Parsed<GoalInput> {
  const t = title(b.title);
  if (!t) return { ok: false, error: "Describe the goal in 3 to 200 characters." };
  const detail = text(b.detail, 2000);
  if (detail === undefined) return { ok: false, error: "The detail can be up to 2,000 characters." };
  const target = isoDate(b.targetDate);
  if (!target) return { ok: false, error: "Every goal needs a target date." };
  const need = optUuid(b.needId);
  if (need === undefined) return { ok: false, error: "That need reference is not valid." };
  return { ok: true, value: { title: t, detail, target_date: target, need_id: need } };
}

export function parseGoalStatus(v: unknown): GoalStatus | null {
  return oneOf(GOAL_STATUS, v);
}

// ── CPD ─────────────────────────────────────────────────────────────────────────────────────────────

export type CpdInput = {
  /** Any configured activity code once 490 is applied; one of 373's nine before. */
  activity_type: CpdActivity | string; title: string; provider: string | null; hours: number | null; cpd_points: number | null;
  activity_date: string; reflection: string | null; goal_id: string | null;
};

/**
 * A CPD entry. Without `opts` it is exactly 373's rule: the nine types, hours required, whole points. With migration 490
 * (`opts.flexible`, LCPD-2) only a meaningful description and the date are required: hours are optional, credits take one
 * decimal, and the activity type is any one the configuration offers (`opts.types`).
 */
export function parseCpd(b: Record<string, unknown>, today: string, opts: { types?: readonly string[]; flexible?: boolean } = {}): Parsed<CpdInput> {
  const allowed: readonly string[] = opts.types ?? CPD_ACTIVITY.map(([c]) => c);
  const type = typeof b.activityType === "string" && allowed.includes(b.activityType) ? b.activityType : null;
  if (!type) return { ok: false, error: "Choose the kind of activity." };
  const t = title(b.title);
  if (!t) return { ok: false, error: "Describe the activity in 3 to 200 characters." };
  const provider = text(b.provider, 160);
  if (provider === undefined) return { ok: false, error: "The provider can be up to 160 characters." };
  const blankHours = b.hours === null || b.hours === undefined || b.hours === "";
  const hours = blankHours ? null : Number(b.hours);
  if (hours === null && !opts.flexible) return { ok: false, error: "Enter the hours as a number above 0 and up to 1,000." };
  if (hours !== null && (!Number.isFinite(hours) || hours <= 0 || hours > 1000)) return { ok: false, error: "Enter the hours as a number above 0 and up to 1,000, or leave them blank." };
  const rawPoints = b.cpdPoints;
  const points = rawPoints === null || rawPoints === undefined || rawPoints === "" ? null : Number(rawPoints);
  if (points !== null && opts.flexible && (!Number.isFinite(points) || points < 0 || points > 1000 || Math.round(points * 10) !== points * 10)) return { ok: false, error: "CPD credits are a number up to 1,000 with at most one decimal, or left blank." };
  if (points !== null && !opts.flexible && (!Number.isInteger(points) || points < 0 || points > 1000)) return { ok: false, error: "CPD points must be a whole number up to 1,000, or left blank." };
  const date = isoDate(b.activityDate);
  if (!date) return { ok: false, error: "Enter the date of the activity." };
  if (date > today) return { ok: false, error: "A CPD activity is recorded once it has happened. The date cannot be in the future." };
  const reflection = text(b.reflection, 5000);
  if (reflection === undefined) return { ok: false, error: "The reflection can be up to 5,000 characters." };
  const goal = optUuid(b.goalId);
  if (goal === undefined) return { ok: false, error: "That goal reference is not valid." };
  return {
    ok: true, value: {
      activity_type: type, title: t, provider, hours: hours === null ? null : Math.round(hours * 10) / 10, cpd_points: points,
      activity_date: date, reflection, goal_id: goal,
    },
  };
}

// ── EVIDENCE ────────────────────────────────────────────────────────────────────────────────────────

export type EvidenceInput = {
  kind: EvidenceKind; title: string; detail: string | null; issuing_body: string | null;
  issued_on: string | null; expires_on: string | null; need_id: string | null;
  framework_id: string | null; framework_competency_id: string | null;
};

export function parseEvidence(b: Record<string, unknown>, today: string): Parsed<EvidenceInput> {
  const kind = oneOf(EVIDENCE_KIND, b.kind);
  if (!kind) return { ok: false, error: "Choose whether this is a credential or competency evidence." };
  const t = title(b.title);
  if (!t) return { ok: false, error: "Name it in 3 to 200 characters." };
  const detail = text(b.detail, 5000);
  if (detail === undefined) return { ok: false, error: "The description can be up to 5,000 characters." };
  const body = text(b.issuingBody, 160);
  if (body === undefined) return { ok: false, error: "The issuing body can be up to 160 characters." };
  const issued = isoDate(b.issuedOn);
  const expires = isoDate(b.expiresOn);
  if (issued === undefined || expires === undefined) return { ok: false, error: "Enter dates as real calendar dates." };
  if (issued && issued > today) return { ok: false, error: "The issue date cannot be in the future." };
  if (kind !== "credential" && expires) return { ok: false, error: "Only a credential has an expiry date." };
  if (issued && expires && expires < issued) return { ok: false, error: "The expiry date cannot be before the issue date." };
  const need = optUuid(b.needId);
  const fw = optUuid(b.frameworkId);
  const comp = optUuid(b.frameworkCompetencyId);
  if (need === undefined || fw === undefined || comp === undefined) return { ok: false, error: "A linked reference is not valid." };
  if (comp && !fw) return { ok: false, error: "Choose the framework the competency belongs to." };
  return {
    ok: true, value: {
      kind, title: t, detail, issuing_body: body, issued_on: issued, expires_on: expires,
      need_id: need, framework_id: fw, framework_competency_id: comp,
    },
  };
}

// ── DOCUMENTS ───────────────────────────────────────────────────────────────────────────────────────

/** The stored object name: the owner's id first (373's CHECK requires it), then a random id. */
export function documentPath(userId: string, fileName: string, random: string): { path: string; name: string } {
  const name = fileName.replace(/[^\w.\-()+ ]/g, "_").slice(0, 120) || "document";
  return { path: `${userId}/${random}-${name}`, name };
}
