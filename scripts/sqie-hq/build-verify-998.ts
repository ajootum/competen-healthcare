// Builds docs/evidence/SQIE-HQ/VERIFY-998.sql. The marker samples come from src/lib/knowledge/safety-markers.samples.ts and the expected
// answer from the application's own hasSafetyMarkers, so the HQ review page and the database hold one rule.
//   npx tsx scripts/sqie-hq/build-verify-998.ts
// Pure: reads nothing, writes the one SQL file. SQIE 998 (owner decision 1, 4 Nov 2026).
import { writeFileSync } from "node:fs";
import { hasSafetyMarkers } from "@/lib/knowledge/safety-markers";
import { MARKER_SAMPLES } from "@/lib/knowledge/safety-markers.samples";

const lit = (v: unknown) => `'${JSON.stringify(v).replace(/'/g, "''")}'::jsonb`;
const ascii = (s: string) => s.replace(/[^\x20-\x7e]/g, "?");
for (const s of MARKER_SAMPLES) if (hasSafetyMarkers(s.content) !== s.markers) throw new Error(`sample disagrees with hasSafetyMarkers: ${s.name}`);
const parity = MARKER_SAMPLES.map(s =>
  `  if ckri_question_has_safety_markers(${lit(s.content)}) is distinct from ${s.markers} then raise exception 'VERIFY-998 FAIL markers rule: ${ascii(s.name)}'; end if; n := n + 1;`).join("\n");

const marked = { format: "short", stem: "Name the first action for a patient with no pulse.", options: [], marking: "deterministic", rationale: "Start chest compressions and call for help.",
  answerKey: { accepted: ["Start chest compressions"], safetyCritical: true, unsafe: ["Wait and reassess"] } };
const unmarked = { format: "short", stem: "Name the normal adult resting heart rate range.", options: [], marking: "deterministic", rationale: "60 to 100 beats per minute.",
  answerKey: { accepted: ["60 to 100"] } };

const sql = `-- VERIFY-998 (strict). GENERATED by scripts/sqie-hq/build-verify-998.ts: do not edit by hand.
-- Run on STAGING after 998. One block that ALWAYS raises, so nothing planted is kept:
--   "VERIFY-998 PASS pass=N"  every check held (reported by the runner as a rolled-back error: nothing changed)
--   "VERIFY-998 FAIL ..."     the first check that did not hold
do $$
declare
  n int := 0;
  bad int;
  v_a uuid; v_b uuid; v_c uuid; v_appt uuid; v_res uuid; v_ver uuid; v_ccv uuid; v_res2 uuid; v_ver2 uuid; v_ccv2 uuid; v_res3 uuid; v_ver3 uuid; v_ccv3 uuid;
  c_marked jsonb := ${lit(marked)};
  c_unmarked jsonb := ${lit(unmarked)};
begin
  -- the objects
  if not exists (select 1 from information_schema.columns where table_name = 'clinical_review_decision' and column_name = 'safety_markers_approved'
                  and is_nullable = 'NO' and column_default = 'false') then raise exception 'VERIFY-998 FAIL column missing or not "not null default false"'; end if; n := n + 1;
  if not exists (select 1 from pg_trigger where tgrelid = 'clinical_review_decision'::regclass and tgname = 'clinical_review_decision_marker_guard' and tgenabled <> 'D')
    then raise exception 'VERIFY-998 FAIL marker guard trigger missing or disabled'; end if; n := n + 1;
  if not (select prosecdef from pg_proc where oid = 'ckri_library_caps_approved(uuid)'::regprocedure) then raise exception 'VERIFY-998 FAIL caps function is not security definer'; end if; n := n + 1;
  if has_function_privilege('anon', 'ckri_library_caps_approved(uuid)', 'execute') or has_function_privilege('authenticated', 'ckri_library_caps_approved(uuid)', 'execute')
    then raise exception 'VERIFY-998 FAIL caps function executable by anon or authenticated'; end if; n := n + 1;
  if not has_function_privilege('service_role', 'ckri_library_caps_approved(uuid)', 'execute') then raise exception 'VERIFY-998 FAIL service_role cannot execute the caps function'; end if; n := n + 1;
  -- every stored marker approval is an approval of a marked revision question
  select count(*) into bad from clinical_review_decision d join clinical_content_version ccv on ccv.id = d.version_id
    left join ckri_knowledge_version kv on kv.id = ccv.knowledge_version_id left join ckri_knowledge_resource r on r.id = kv.resource_id
   where d.safety_markers_approved and (d.decision <> 'approved' or ccv.content_kind <> 'resource' or r.kind is distinct from 'revision_question' or not ckri_question_has_safety_markers(ccv.content_snapshot));
  if bad <> 0 then raise exception 'VERIFY-998 FAIL % stored marker approval(s) on something else', bad; end if; n := n + 1;

  -- the markers rule, sample by sample (expected = the application's hasSafetyMarkers)
${parity}

  -- planted: a published revision question with markers. The 442/395/640/641/690 guards are disabled INSIDE this transaction only.
  -- The 998 marker guard stays ENABLED: it is what is tested.
  alter table ckri_knowledge_resource disable trigger ckri_knowledge_resource_guard;
  alter table ckri_knowledge_version disable trigger user;
  alter table clinical_content_version disable trigger user;
  alter table clinical_review_decision disable trigger clinical_review_decision_guard;
  alter table clinical_review_decision disable trigger clinical_review_decision_scope_guard;
  alter table clinical_review_decision disable trigger clinical_review_decision_sod_guard;
  alter table clinical_review_decision disable trigger clinical_review_decision_method_sod_690;
  select id into v_a from profiles order by created_at limit 1;
  select id into v_b from profiles order by created_at offset 1 limit 1;
  select id into v_c from profiles order by created_at offset 2 limit 1;
  select id into v_appt from ogs_office_appointments order by created_at limit 1;
  insert into ckri_knowledge_resource (code, kind, title, created_by) values ('verify-998-marked', 'revision_question', 'VERIFY 998 marked', v_a) returning id into v_res;
  insert into ckri_knowledge_version (resource_id, version_no, content, origin, authored_by, state, content_hash, educator_reviewed_by, educator_reviewed_hash, educator_reviewed_at, submitted_by, submitted_at, published_by, published_at)
    values (v_res, 1, c_marked, 'educator', array[v_a], 'published', 'verify-998', v_a, 'verify-998', now(), v_a, now(), v_a, now()) returning id into v_ver;
  insert into clinical_content_version (content_kind, knowledge_version_id, content_hash, content_snapshot, authored_by, submitted_by, required_approvals)
    values ('resource', v_ver, 'verify-998', c_marked, array[v_a], v_a, 1) returning id into v_ccv;

  -- 1. approved WITHOUT the marker approval: approved, not capped
  insert into clinical_review_decision (version_id, reviewer_id, appointment_id, decision) values (v_ccv, v_a, v_appt, 'approved');
  if not ckri_knowledge_approved(v_ver) then raise exception 'VERIFY-998 FAIL planted version not approved'; end if; n := n + 1;
  if ckri_library_caps_approved(v_ver) then raise exception 'VERIFY-998 FAIL capped without an explicit marker approval'; end if; n := n + 1;
  if (select safety_markers_approved from clinical_review_decision where version_id = v_ccv and reviewer_id = v_a) then raise exception 'VERIFY-998 FAIL a decision without it reads approved'; end if; n := n + 1;
  -- 2. the marker approval refused on a rejection
  begin
    insert into clinical_review_decision (version_id, reviewer_id, appointment_id, decision, comment, safety_markers_approved) values (v_ccv, v_c, v_appt, 'rejected', 'x', true);
    raise exception 'VERIFY-998 FAIL marker approval stored on a rejection';
  exception when others then
    if sqlerrm not like '%approved only with an approval%' then raise exception 'VERIFY-998 FAIL wrong refusal (rejection): %', sqlerrm; end if;
  end; n := n + 1;
  -- 3. an independent reviewer approves the markers explicitly: capped
  insert into clinical_review_decision (version_id, reviewer_id, appointment_id, decision, safety_markers_approved) values (v_ccv, v_b, v_appt, 'approved', true);
  if not ckri_library_caps_approved(v_ver) then raise exception 'VERIFY-998 FAIL not capped after the explicit marker approval'; end if; n := n + 1;
  -- 4. more approvals required than confirmed the markers: not capped
  update clinical_content_version set required_approvals = 2 where id = v_ccv;
  if not ckri_knowledge_approved(v_ver) then raise exception 'VERIFY-998 FAIL two approvals not approved'; end if; n := n + 1;
  if ckri_library_caps_approved(v_ver) then raise exception 'VERIFY-998 FAIL capped with 1 marker approval of 2 required'; end if; n := n + 1;
  update clinical_content_version set required_approvals = 1 where id = v_ccv;
  -- 5. not published: not capped
  update ckri_knowledge_version set state = 'retired' where id = v_ver;
  if ckri_library_caps_approved(v_ver) then raise exception 'VERIFY-998 FAIL capped while not published'; end if; n := n + 1;
  update ckri_knowledge_version set state = 'published' where id = v_ver;
  -- 6. content changed since the decisions: not capped
  update ckri_knowledge_version set content_hash = 'verify-998-changed', educator_reviewed_hash = 'verify-998-changed' where id = v_ver;
  if ckri_library_caps_approved(v_ver) then raise exception 'VERIFY-998 FAIL capped on content the reviewers did not see'; end if; n := n + 1;
  update ckri_knowledge_version set content_hash = 'verify-998', educator_reviewed_hash = 'verify-998' where id = v_ver;
  if not ckri_library_caps_approved(v_ver) then raise exception 'VERIFY-998 FAIL restore'; end if;
  -- 7. a rejection by anyone: not capped
  insert into clinical_review_decision (version_id, reviewer_id, appointment_id, decision, comment) values (v_ccv, v_c, v_appt, 'rejected', 'x');
  if ckri_library_caps_approved(v_ver) then raise exception 'VERIFY-998 FAIL capped despite a rejection'; end if; n := n + 1;

  -- 8. a version with no markers: the approval is refused, and it is never capped
  insert into ckri_knowledge_resource (code, kind, title, created_by) values ('verify-998-unmarked', 'revision_question', 'VERIFY 998 unmarked', v_a) returning id into v_res2;
  insert into ckri_knowledge_version (resource_id, version_no, content, origin, authored_by, state, content_hash, educator_reviewed_by, educator_reviewed_hash, educator_reviewed_at, submitted_by, submitted_at, published_by, published_at)
    values (v_res2, 1, c_unmarked, 'educator', array[v_a], 'published', 'verify-998-u', v_a, 'verify-998-u', now(), v_a, now(), v_a, now()) returning id into v_ver2;
  insert into clinical_content_version (content_kind, knowledge_version_id, content_hash, content_snapshot, authored_by, submitted_by, required_approvals)
    values ('resource', v_ver2, 'verify-998-u', c_unmarked, array[v_a], v_a, 1) returning id into v_ccv2;
  begin
    insert into clinical_review_decision (version_id, reviewer_id, appointment_id, decision, safety_markers_approved) values (v_ccv2, v_b, v_appt, 'approved', true);
    raise exception 'VERIFY-998 FAIL marker approval stored on a version with no markers';
  exception when others then
    if sqlerrm not like '%carries no safety marker%' then raise exception 'VERIFY-998 FAIL wrong refusal (no markers): %', sqlerrm; end if;
  end; n := n + 1;
  insert into clinical_review_decision (version_id, reviewer_id, appointment_id, decision) values (v_ccv2, v_b, v_appt, 'approved');
  if ckri_library_caps_approved(v_ver2) then raise exception 'VERIFY-998 FAIL an unmarked version reads capped'; end if; n := n + 1;

  -- 9. not a revision question: refused
  insert into ckri_knowledge_resource (code, kind, title, created_by) values ('verify-998-expl', 'explanation', 'VERIFY 998 explanation', v_a) returning id into v_res3;
  insert into ckri_knowledge_version (resource_id, version_no, content, origin, authored_by, state, content_hash, educator_reviewed_by, educator_reviewed_hash, educator_reviewed_at, submitted_by, submitted_at, published_by, published_at)
    values (v_res3, 1, c_marked, 'educator', array[v_a], 'published', 'verify-998-e', v_a, 'verify-998-e', now(), v_a, now(), v_a, now()) returning id into v_ver3;
  insert into clinical_content_version (content_kind, knowledge_version_id, content_hash, content_snapshot, authored_by, submitted_by, required_approvals)
    values ('resource', v_ver3, 'verify-998-e', c_marked, array[v_a], v_a, 1) returning id into v_ccv3;
  begin
    insert into clinical_review_decision (version_id, reviewer_id, appointment_id, decision, safety_markers_approved) values (v_ccv3, v_b, v_appt, 'approved', true);
    raise exception 'VERIFY-998 FAIL marker approval stored on an explanation';
  exception when others then
    if sqlerrm not like '%only on a library revision question%' then raise exception 'VERIFY-998 FAIL wrong refusal (kind): %', sqlerrm; end if;
  end; n := n + 1;
  if ckri_library_caps_approved(gen_random_uuid()) then raise exception 'VERIFY-998 FAIL an unknown version reads capped'; end if; n := n + 1;

  raise exception 'VERIFY-998 PASS pass=%', n;
end
$$;
`;
writeFileSync("docs/evidence/SQIE-HQ/VERIFY-998.sql", sql.replace(/\r/g, ""));
console.log(`VERIFY-998.sql written: ${MARKER_SAMPLES.length} marker samples`);
