-- MIGRATION 1000: COMPETEN SCHOLAR -- THE PERSONAL NOTEBOOK (COMPETEN-NOTEBOOK-001 P1, SCHOLAR-NOTEBOOK-UX-002)
--
-- Owner instructions of 6 Nov 2026. My Notebook and free-form capture are the 820 note table, widened. No second store,
-- no new table. Additive: new nullable columns, widened CHECKs, indexes, two triggers on delete, replaced 820 functions.
--
-- 1. FREE-STANDING NOTES. target_kind free: a note with no artefact, material, section or lesson. Only kind note may be
--    free, and only with a client_key (below). Every 820 and 975 rule for the other targets is unchanged.
--
-- 2. LONG-FORM WRITING. A note body may be up to 50000 characters. Highlights and summaries keep their 4000.
--
-- 3. ORGANISING. title (optional), tags (optional, at most 12), pinned_at, all written only by the learner.
--
-- 4. SAFE AUTOSAVE. client_key is made by the page before the first save, so a retry after a lost reply finds the same
--    note and never makes a second one (plain unique index, nulls are distinct). revision goes up on every update, by
--    trigger, so a save made from an old copy is refused and nothing is overwritten unseen. Both are set by the schema.
--
-- 5. WHERE IT WAS WRITTEN. section_label (the section heading as the learner saw it), section_anchor (the 790 lesson
--    anchor, to return to the place), captured_in (the Scholar space), competency_id (a hint checked by the store, as
--    chunk_id is, because a framework competency is not a learner row) and study_id (a composite key onto the learner
--    own session, set null when it goes).
--
-- 6. A NOTE OUTLIVES ITS SOURCE. 820 cascades a note away with its material or session. A note written through the
--    Notebook (client_key set, kind note) is the learner own writing and is detached first: it stays, as a free note, or on
--    its section where only the lesson went, and was_on says what it was linked to. Highlights, bookmarks, summaries and
--    notes written before this migration still go with what they are on, as before. Erasure still removes everything.
--
-- 7. SEARCH. search_tsv: title, tags, body and quote, generated by the database. individual_scholar_library_search is
--    replaced with the same signature and result, reading search_tsv, so a title or a tag is found by every search. New
--    individual_scholar_notebook_search: word-prefix full text over one learner own notes, deterministic, no AI.
--
-- 8. THE MARKER. individual_scholar_notebook_1000() returns true. The application asks it once, because a widened CHECK
--    cannot be seen by a select. SECURITY INVOKER, reads nothing, service_role only.
--
-- PRIVATE AND ERASABLE. No RLS change: read own, one policy, no table grants. Nothing here is read by Professional, by any
-- employer surface or by the HQ plane. No AI: nothing in this file sends or reads a note for a model.
--
-- APPLY ON STAGING ONLY. NOT AUTHORISED FOR PRODUCTION without a separate owner GO. Depends on 372, 414, 820, 975. Needs
-- PostgreSQL 15 or later (as 820). Re-running it is a no-op. Rollback: docs/evidence/COMPETEN-NOTEBOOK-001/ROLLBACK-1000.sql
-- (refuses while any note written through the Notebook exists).
--
-- FAIL CLOSED WITHOUT IT. The marker is absent, so policy scholar_personal_notebook cannot turn anything on: no Quick Note,
-- no boxes in Learn, no My Notebook leaf, and the routes answer 409. Every 820 and 975 path works as it does today.
--
-- HOUSE RULES. ASCII only. No semicolons inside comments. No partial unique index. notify pgrst last.
-- ====================================================================================================

