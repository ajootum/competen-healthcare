-- ---- 4. FULL TEXT -------------------------------------------------------------------------------------------
-- array_to_string is stable only because an array of any type may print differently. Here the array is always text, so
-- the wrapper is safely immutable, which a generated column needs.

create or replace function public.individual_scholar_note_search_doc(p_title text, p_tags text[], p_body text, p_quote text)
returns tsvector
language sql
immutable
set search_path = public, pg_catalog
as $$
  select setweight(to_tsvector('english'::regconfig, coalesce(p_title, '')), 'A')
      || setweight(to_tsvector('english'::regconfig, coalesce(array_to_string(p_tags, ' '), '')), 'B')
      || setweight(to_tsvector('english'::regconfig, coalesce(p_body, '') || ' ' || coalesce(p_quote, '')), 'C')
$$;

alter table individual_scholar_note add column if not exists search_tsv tsvector
  generated always as (public.individual_scholar_note_search_doc(title, tags, body, quote)) stored;

create index if not exists idx_individual_scholar_note_search_tsv
  on individual_scholar_note using gin (search_tsv);

-- ---- 5. THE UPDATE TRIGGER: revision and the identity of a note ---------------------------------------------
-- updated_at is when the learner last changed their words. Pinning or moving a link is not an edit.

create or replace function public.individual_scholar_note_touch()
returns trigger
language plpgsql
set search_path = public, pg_catalog
as $$
begin
  if new.body is distinct from old.body or new.title is distinct from old.title or new.tags is distinct from old.tags then
    new.updated_at := now();
  else
    new.updated_at := old.updated_at;
  end if;
  new.revision := old.revision + 1;
  new.created_at := old.created_at;
  new.user_id := old.user_id;
  new.client_key := old.client_key;
  return new;
end;
$$;

-- ---- 6. A NOTE OUTLIVES ITS SOURCE ---------------------------------------------------------------------------

create or replace function public.individual_scholar_note_detach_material()
returns trigger
language plpgsql
set search_path = public, pg_catalog
as $$
begin
  update individual_scholar_note
     set target_kind = 'free', artefact_id = null, material_id = null, chunk_id = null, session_id = null, step = null,
         was_on = left(old.title, 300)
   where user_id = old.user_id and material_id = old.id and client_key is not null and kind = 'note';
  return old;
end;
$$;

create or replace function public.individual_scholar_note_detach_session()
returns trigger
language plpgsql
set search_path = public, pg_catalog
as $$
begin
  update individual_scholar_note
     set target_kind = case when material_id is null then 'free' when chunk_id is null then 'material' else 'section' end,
         session_id = null, step = null,
         was_on = case when material_id is null then left(old.title, 300) else was_on end
   where user_id = old.user_id and session_id = old.id and client_key is not null and kind = 'note';
  return old;
end;
$$;

drop trigger if exists individual_scholar_note_detach_material on individual_scholar_material;
create trigger individual_scholar_note_detach_material before delete on individual_scholar_material
  for each row execute function public.individual_scholar_note_detach_material();

drop trigger if exists individual_scholar_note_detach_session on individual_scholar_learning_session;
create trigger individual_scholar_note_detach_session before delete on individual_scholar_learning_session
  for each row execute function public.individual_scholar_note_detach_session();

-- ---- 7. THE LIBRARY SEARCH, READING search_tsv. Same signature and result as 820 ------------------------------

create or replace function public.individual_scholar_library_search(p_user_id uuid, p_query text, p_limit integer, p_offset integer)
returns table (kind text, id uuid, material_id uuid, session_id uuid, step integer, artefact_id uuid, chunk_id uuid,
  label text, headline text, rank real, created_at timestamptz, total bigint)
language sql
stable
security invoker
set search_path = public, pg_catalog
as $$
  with q as (
    select websearch_to_tsquery('english', left(coalesce(p_query, ''), 200)) as tsq
  ), hits as (
    select 'artefact'::text as kind, a.id, a.material_id, a.session_id, a.step, a.id as artefact_id, null::uuid as chunk_id,
           a.action as label, a.content as doc, ts_rank(a.tsv, q.tsq) as rank, a.created_at
      from individual_scholar_artefact a, q
     where a.user_id = p_user_id and a.superseded_at is null and a.tsv @@ q.tsq
    union all
    select 'note', n.id, n.material_id, n.session_id, n.step, n.artefact_id, n.chunk_id,
           n.kind, coalesce(n.title || ' ', '') || coalesce(n.body, '') || ' ' || coalesce(n.quote, ''), ts_rank(n.search_tsv, q.tsq), n.created_at
      from individual_scholar_note n, q
     where n.user_id = p_user_id and n.search_tsv @@ q.tsq
    union all
    select 'lesson', s.id, null::uuid, s.id, null::integer, null::uuid, null::uuid,
           s.status, s.title || coalesce(' ' || s.topic, ''), ts_rank(to_tsvector('english', s.title || ' ' || coalesce(s.topic, '')), q.tsq), s.last_active_at
      from individual_scholar_learning_session s, q
     where s.user_id = p_user_id and to_tsvector('english', s.title || ' ' || coalesce(s.topic, '')) @@ q.tsq
    union all
    select 'flashcard', c.id, c.material_id, null::uuid, null::integer, null::uuid, c.chunk_id,
           c.stem, c.stem || ' ' || coalesce(c.answer ->> 'back', ''), ts_rank(to_tsvector('english', c.stem || ' ' || coalesce(c.answer ->> 'back', '')), q.tsq), c.created_at
      from individual_scholar_question c, q
     where c.user_id = p_user_id and c.kind = 'flashcard' and to_tsvector('english', c.stem || ' ' || coalesce(c.answer ->> 'back', '')) @@ q.tsq
    union all
    select 'card_note', m.question_id, c.material_id, null::uuid, null::integer, null::uuid, c.chunk_id,
           c.stem, m.note, ts_rank(to_tsvector('english', m.note), q.tsq), m.updated_at
      from individual_scholar_flashcard_mark m
      join individual_scholar_question c on c.id = m.question_id and c.user_id = p_user_id, q
     where m.user_id = p_user_id and m.note is not null and to_tsvector('english', m.note) @@ q.tsq
  ), page as (
    select h.*, count(*) over () as total
      from hits h
     order by h.rank desc, h.created_at desc, h.id
     limit least(greatest(coalesce(p_limit, 25), 1), 50)
    offset least(greatest(coalesce(p_offset, 0), 0), 5000)
  )
  select p.kind, p.id, p.material_id, p.session_id, p.step, p.artefact_id, p.chunk_id, left(p.label, 300),
         ts_headline('english', replace(replace(p.doc, '{{hl}}', ''), '{{/hl}}', ''), q.tsq,
           'StartSel={{hl}}, StopSel={{/hl}}, MaxWords=30, MinWords=12, MaxFragments=2, FragmentDelimiter=" ... "'),
         p.rank, p.created_at, p.total
    from page p, q
   order by p.rank desc, p.created_at desc, p.id
$$;

-- ---- 8. THE NOTEBOOK SEARCH: every word as a prefix, so a part-typed word finds its note ----------------------

create or replace function public.individual_scholar_notebook_search(p_user_id uuid, p_query text, p_limit integer, p_offset integer)
returns table (id uuid, headline text, rank real, total bigint)
language sql
stable
security invoker
set search_path = public, pg_catalog
as $$
  with q as (
    select to_tsquery('english', array_to_string(array(
             select quote_literal(w) || ':*'
               from regexp_split_to_table(lower(regexp_replace(left(coalesce(p_query, ''), 200), '[^[:alnum:]]+', ' ', 'g')), ' ') as w
              where w <> ''
              limit 8), ' & ')) as tsq
  ), hits as (
    select n.id, coalesce(n.title || ' ', '') || coalesce(n.body, '') || ' ' || coalesce(n.quote, '') || ' ' || array_to_string(n.tags, ' ') as doc,
           ts_rank(n.search_tsv, q.tsq) as rank, n.updated_at
      from individual_scholar_note n, q
     where n.user_id = p_user_id and n.kind <> 'bookmark' and n.search_tsv @@ q.tsq
  ), page as (
    select h.*, count(*) over () as total
      from hits h
     order by h.rank desc, h.updated_at desc, h.id
     limit least(greatest(coalesce(p_limit, 25), 1), 50)
    offset least(greatest(coalesce(p_offset, 0), 0), 5000)
  )
  select p.id,
         ts_headline('english', replace(replace(p.doc, '{{hl}}', ''), '{{/hl}}', ''), q.tsq,
           'StartSel={{hl}}, StopSel={{/hl}}, MaxWords=30, MinWords=12, MaxFragments=2, FragmentDelimiter=" ... "'),
         p.rank, p.total
    from page p, q
   order by p.rank desc, p.updated_at desc, p.id
$$;

